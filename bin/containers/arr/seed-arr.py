def req(base, key, path, method="GET", body=None):
    r = urllib.request.Request(
        base + path,
        data=json.dumps(body).encode() if body is not None else None,
        method=method,
        headers={"X-Api-Key": key, "Content-Type": "application/json"},
    )
    try:
        with urllib.request.urlopen(r, timeout=3) as res:
            raw = res.read()
            return json.loads(raw) if raw else None
    except urllib.error.HTTPError as e:
        print(e.code, e.read().decode()[:500], file=sys.stderr)
        raise


def wait_for(url):
    for _ in range(60):
        try:
            urllib.request.urlopen(url, timeout=5).read()
            return
        except urllib.error.HTTPError:
            return  # server answered (e.g. 401/403) => it is up
        except Exception:
            time.sleep(2)
    sys.exit(f"timeout waiting for {url}")


def set_fields(item, values):
    for f in item["fields"]:
        if f["name"] in values:
            f["value"] = values[f["name"]]
    return item


def pick(schema, implementation):
    return next(s for s in schema if s["implementation"] == implementation)


