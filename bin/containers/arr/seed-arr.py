#!/usr/bin/env python3
"""Configure the arr stack without the UI. Stdlib only, idempotent.
Usage: podman compose up -d && python3 bootstrap.py   (run from the folder with .env)
"""
import http.cookiejar
import json
import os
import re
import secrets
import subprocess
import sys
import time
import urllib.error
import urllib.parse
import urllib.request
from pathlib import Path


ENV_PATH = Path(__file__).resolve().parent / ".env"   # same folder as compose.yaml


def create_env(path: Path):
    """Write a .env with sane defaults and freshly generated secrets (chmod 600)."""
    content = f"""# Generated by bootstrap.py. Never commit this file (contains secrets).

# ---- REQUIRED: TODO, fill these in ----
# Mullvad: https://mullvad.net/en/account/wireguard-config -> download .conf -> [Interface] section
# TODO: PrivateKey from the .conf
WIREGUARD_PRIVATE_KEY=
# TODO: Address from the .conf, IPv4 part only, e.g. 10.64.222.21/32
WIREGUARD_ADDRESSES=

# ---- REQUIRED: generated for you, no action needed ----
RADARR_API_KEY={secrets.token_hex(16)}
LIDARR_API_KEY={secrets.token_hex(16)}
PROWLARR_API_KEY={secrets.token_hex(16)}
QBT_PASSWORD={secrets.token_urlsafe(12)}

# ---- OPTIONAL: defaults shown, change only if needed ----
# Where configs, downloads and media live
ARR_ROOT=/media/cesc/data/arr
# Owner of created files (detected from your user: `id -u`, `id -g`)
PUID={os.getuid()}
PGID={os.getgid()}
# Timezone for logs/schedules, e.g. Europe/Zurich
TZ=UTC
# Mullvad server filters; leave both empty for any server
SERVER_COUNTRIES=Switzerland
SERVER_CITIES=
"""
    fd = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
    with os.fdopen(fd, "w") as f:
        f.write(content)
    sys.exit(
        f"Created {path} with defaults and generated keys.\n"
        "Next: fill the TODO values (WIREGUARD_PRIVATE_KEY, WIREGUARD_ADDRESSES), then\n"
        "  podman compose up -d && python3 " + Path(__file__).name
    )


def load_env(path=ENV_PATH):
    if not path.exists():
        create_env(path)
    for line in path.read_text().splitlines():
        line = line.split(" #")[0].strip()
        if line and not line.startswith("#") and "=" in line:
            k, v = line.split("=", 1)
            os.environ.setdefault(k.strip(), v.strip().strip("'\""))


load_env()
TODO_VARS = ["WIREGUARD_PRIVATE_KEY", "WIREGUARD_ADDRESSES"]   # no usable default
missing = [k for k in TODO_VARS if not os.getenv(k)]
if missing:
    sys.exit(f"TODO: set {', '.join(missing)} in {ENV_PATH}, then run `podman compose up -d` and this script again.")
ARR_ROOT = Path(os.getenv("ARR_ROOT", "/media/cesc/data/arr"))


def key_from(path: Path):  # fallback if no *_API_KEY in env: read it from the app's config.xml
    try:
        return path.read_text().split("<ApiKey>")[1].split("</ApiKey>")[0]
    except (FileNotFoundError, IndexError):
        return None


RADARR = os.getenv("RADARR_URL", "http://127.0.0.1:7878").rstrip("/")
LIDARR = os.getenv("LIDARR_URL", "http://127.0.0.1:8686").rstrip("/")
PROWLARR = os.getenv("PROWLARR_URL", "http://127.0.0.1:9696").rstrip("/")
QB = os.getenv("QBIT_URL", "http://127.0.0.1:8081").rstrip("/")
RKEY = os.getenv("RADARR_API_KEY") or key_from(ARR_ROOT / "config/radarr/config.xml")
LKEY = os.getenv("LIDARR_API_KEY") or key_from(ARR_ROOT / "config/lidarr/config.xml")
PKEY = os.getenv("PROWLARR_API_KEY") or key_from(ARR_ROOT / "config/prowlarr/config.xml")
QB_PASS = os.getenv("QBT_PASSWORD") or sys.exit("QBT_PASSWORD missing in .env")
QB_USER = "admin"
QB_HOST, QB_PORT = "gluetun", 8081      # as seen from the other containers
QB_SUBNET = "172.28.0.0/24"             # must match the arr network subnet in compose.yaml
INDEXERS = ["1337x", "the pirate bay", "nyaa", "eztv", "yts"]   # name prefixes, case-insensitive
NEEDS_FLARESOLVERR = {"1337x"}
for name, k in (("RADARR", RKEY), ("LIDARR", LKEY), ("PROWLARR", PKEY)):
    if not k:
        sys.exit(f"{name}_API_KEY missing in .env")


def req(base, key, path, method="GET", body=None):
    r = urllib.request.Request(
        base + path,
        data=json.dumps(body).encode() if body is not None else None,
        method=method,
        headers={"X-Api-Key": key, "Content-Type": "application/json"},
    )
    try:
        with urllib.request.urlopen(r, timeout=30) as res:
            raw = res.read()
            return json.loads(raw) if raw else None
    except urllib.error.HTTPError as e:
        print(e.code, e.read().decode()[:500], file=sys.stderr)
        raise


def wait_for(url):
    for _ in range(60):
        try:
            urllib.request.urlopen(url, timeout=5).read()
            return
        except urllib.error.HTTPError:
            return  # server answered (e.g. 401/403) => it is up
        except Exception:
            time.sleep(2)
    sys.exit(f"timeout waiting for {url}")


def set_fields(item, values):
    for f in item["fields"]:
        if f["name"] in values:
            f["value"] = values[f["name"]]
    return item


def pick(schema, implementation):
    return next(s for s in schema if s["implementation"] == implementation)


print("Waiting for services...")
for u in (f"{RADARR}/ping", f"{LIDARR}/ping", f"{PROWLARR}/ping", f"{QB}/"):
    wait_for(u)

# ---------- 1. qBittorrent: credentials, save path, categories ----------
# https://github.com/qbittorrent/qBittorrent/wiki/WebUI-API-(qBittorrent-5.0)
opener = urllib.request.build_opener(urllib.request.HTTPCookieProcessor(http.cookiejar.CookieJar()))


def qb_post(path, data):
    r = urllib.request.Request(
        QB + path, data=urllib.parse.urlencode(data).encode(), headers={"Referer": QB}
    )
    return opener.open(r, timeout=30).read().decode()


def qb_login(pw):
    return qb_post("/api/v2/auth/login", {"username": QB_USER, "password": pw}).strip() == "Ok."


if not qb_login(QB_PASS):  # first run: qBittorrent logs a temporary password
    logs = subprocess.run(["podman", "logs", "qbittorrent"], capture_output=True, text=True)
    found = re.findall(r"temporary password is provided for this session: (\S+)", logs.stdout + logs.stderr)
    if not (found and qb_login(found[-1])):
        sys.exit("qBittorrent login failed (check QBT_PASSWORD / `podman logs qbittorrent`)")
qb_post("/api/v2/app/setPreferences", {"json": json.dumps({
    "save_path": "/data/torrents",
    "web_ui_username": QB_USER,
    "web_ui_password": QB_PASS,
    "bypass_auth_subnet_whitelist_enabled": True,
    "bypass_auth_subnet_whitelist": QB_SUBNET,
})})
for cat in ("radarr", "lidarr"):
    try:
        qb_post("/api/v2/torrents/createCategory", {"category": cat, "savePath": f"/data/torrents/{cat}"})
    except urllib.error.HTTPError:
        pass  # 409 = exists
print("qbittorrent configured")


# ---------- 2. Radarr / Lidarr: root folder + qBittorrent client ----------
def add_qbt(base, key, ver, cat_field, cat):
    path = f"/api/{ver}/downloadclient"
    if any(c["name"] == "qBittorrent" for c in req(base, key, path)):
        return
    item = set_fields(pick(req(base, key, path + "/schema"), "QBittorrent"), {
        "host": QB_HOST, "port": QB_PORT, "username": QB_USER, "password": QB_PASS, cat_field: cat,
    })
    item.update(name="qBittorrent", enable=True)
    req(base, key, path + "?forceSave=true", "POST", item)


def has_root(base, key, ver, folder):
    return any(r["path"].rstrip("/") == folder for r in req(base, key, f"/api/{ver}/rootfolder"))


if not has_root(RADARR, RKEY, "v3", "/data/media/movies"):
    req(RADARR, RKEY, "/api/v3/rootfolder", "POST", {"path": "/data/media/movies"})
add_qbt(RADARR, RKEY, "v3", "movieCategory", "radarr")
print("radarr configured")

if not has_root(LIDARR, LKEY, "v1", "/data/media/music"):
    req(LIDARR, LKEY, "/api/v1/rootfolder", "POST", {
        "name": "Music",
        "path": "/data/media/music",
        "defaultQualityProfileId": req(LIDARR, LKEY, "/api/v1/qualityprofile")[0]["id"],
        "defaultMetadataProfileId": req(LIDARR, LKEY, "/api/v1/metadataprofile")[0]["id"],
        "defaultMonitorOption": "all",
        "defaultNewItemMonitorOption": "all",
        "defaultTags": [],
    })
add_qbt(LIDARR, LKEY, "v1", "musicCategory", "lidarr")
print("lidarr configured")

# ---------- 3. Prowlarr: apps, FlareSolverr proxy, indexers ----------
existing = {a["name"] for a in req(PROWLARR, PKEY, "/api/v1/applications")}
for name, base_url, key in (("Radarr", "http://radarr:7878", RKEY), ("Lidarr", "http://lidarr:8686", LKEY)):
    if name in existing:
        continue
    item = set_fields(pick(req(PROWLARR, PKEY, "/api/v1/applications/schema"), name), {
        "prowlarrUrl": "http://prowlarr:9696", "baseUrl": base_url, "apiKey": key,
    })
    item.update(name=name, syncLevel="fullSync")
    req(PROWLARR, PKEY, "/api/v1/applications?forceSave=true", "POST", item)

tags = {t["label"]: t["id"] for t in req(PROWLARR, PKEY, "/api/v1/tag")}
if "flaresolverr" not in tags:
    tags["flaresolverr"] = req(PROWLARR, PKEY, "/api/v1/tag", "POST", {"label": "flaresolverr"})["id"]
fs_tag = tags["flaresolverr"]
if not any(p["name"] == "FlareSolverr" for p in req(PROWLARR, PKEY, "/api/v1/indexerProxy")):
    item = set_fields(pick(req(PROWLARR, PKEY, "/api/v1/indexerProxy/schema"), "FlareSolverr"),
                      {"host": "http://flaresolverr:8191/"})
    item.update(name="FlareSolverr", tags=[fs_tag])
    req(PROWLARR, PKEY, "/api/v1/indexerProxy?forceSave=true", "POST", item)

have = {i["name"].lower() for i in req(PROWLARR, PKEY, "/api/v1/indexer")}
profile_id = req(PROWLARR, PKEY, "/api/v1/appprofile")[0]["id"]
for item in req(PROWLARR, PKEY, "/api/v1/indexer/schema"):
    n = item.get("name", "")
    if not any(n.lower().startswith(w) for w in INDEXERS) or n.lower() in have:
        continue
    item.update(appProfileId=profile_id, enable=True)
    if any(n.lower().startswith(w) for w in NEEDS_FLARESOLVERR):
        item["tags"] = [fs_tag]
    try:
        req(PROWLARR, PKEY, "/api/v1/indexer?forceSave=true", "POST", item)
        print("prowlarr indexer added:", n)
    except Exception as e:
        print("prowlarr indexer skipped:", n, "->", e)
print("prowlarr configured")
